import assert from 'node:assert/strict';
import {readFileSync, writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
const dir = path.resolve(process.argv[2]);
writeFileSync(path.join(dir, 'package.json'), '{"type":"module"}');
writeFileSync(path.join(dir, 'external.js'), 'export const external = "external value";');
const facade = await import(pathToFileURL(path.join(dir, 'public.js')));
const implementation = await import(pathToFileURL(path.join(dir, 'implementation.js')));
const again = await import(pathToFileURL(path.join(dir, 'again.js')));
assert.deepEqual(Object.keys(facade).sort(), ['external', 'next']);
assert.equal(facade.external, 'external value');
assert.equal(facade.next, implementation.next);
assert.equal(again.next, facade.next);
assert.equal(again.own, 'kept');
assert.equal(facade.next(), 1);
assert.equal(implementation.next(), 2);
const types = readFileSync(path.join(dir, 'public.d.ts'), 'utf8');
assert.match(types, /export type \{ Item \} from "\.\/implementation.js";/);
assert.match(types, /export \{ next \} from "\.\/implementation.js";/);
assert.doesNotMatch(readFileSync(path.join(dir, 'public.js'), 'utf8'), /\bItem\b/);
console.log('lib: re-exported entries ok');
